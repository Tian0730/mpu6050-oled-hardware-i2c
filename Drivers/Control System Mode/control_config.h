#ifndef _CONTROL_CONFIG_H_
#define _CONTROL_CONFIG_H_

#include "car_config.h"

/* ================================================================
 *  控制环配置开关
 *  1 = 启用, 0 = 禁用
 *  可独立启用角度环/位置环/速度环，也可同时启用（多环控制）
 *
 *  调试建议：
 *    单独调试速度环 → USE_SPEED_CONTROL=1, 其余=0
 *    单独调试角度环 → USE_ANGLE_CONTROL=1,  其余=0
 *    单独调试位置环 → USE_FOLLOW_CONTROL=1, 其余=0
 *    双环(角度+位置) → 两个都=1
 * ================================================================ */
#define USE_ANGLE_CONTROL   1   // 角度环控制 (MPU6050 + turn)
#define USE_FOLLOW_CONTROL  1   // 位置环控制 (灰度传感器 + follow)
#define USE_SPEED_CONTROL   0   // 速度环控制 (编码器 + speed_control)
#define USE_GYRO_RATE_CONTROL 0 // 角速度环控制 (陀螺仪 Z 轴 + gyro_rate_control)

/* ================================================================
 * 角速度环 180° 转弯测试（独立模式，最高优先级）
 * 1 = 测试模式, 0 = 正常循线
 * ================================================================ */
#define USE_GYRO_RATE_TEST      0

/* ================================================================
 * 循线模式切换
 * 0 = 正方形赛道（直角转弯）
 * 1 = 半圆形赛道（连续弯道循线）
 * 2 = 半圆形赛道（串级 PID 版本）
 * ================================================================ */
#define USE_SEMICIRCLE_FOLLOW       1
#define USE_SEMICIRCLE_FOLLOW_PLUS  0

/* ================================================================
 * 超声波模块启用开关
 * 1 = 避障模式, 0 = 循迹模式
 * ================================================================ */
#define USE_OBSTACLE_AVOIDANCE  0   // 模式切换

#define USE_VOFA_DEBUG          0   // VOFA+串口在线调参

#endif  /* _CONTROL_CONFIG_H_ */